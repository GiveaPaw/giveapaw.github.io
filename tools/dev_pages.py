"""Writes dev-pages.js: the list of public pages the developer page (dev.html) shows and checks.

Run from the repository root after adding, renaming or removing a page:
    python tools/dev_pages.py

Each page gets its <title>, the menu group it sits in (from site_infra.NAV_GROUPS) and a short
"kind". Private and local-only pages are left out (see PRIVATE): never list them on the public site.
"""
import html
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import site_infra  # noqa: E402

# Never on the public site: private grading, demos and prototypes that stay on this computer.
PRIVATE = {
    "judges.html", "demo-update-view.html", "mesh-check-a.html", "mesh-check-b.html", "mesh-check-c.html",
    "iteration-a.html", "iteration-b.html", "iteration-c.html", "iteration-options.html",
    "case-history-options.html", "walkthrough-guide-options.html", "import-browser-samples.html",
    "grading-editor.html", "answer-key-editor.html", "sweep-studio.html",
    "ntop-blocks.html", "my-presentations.html", "dev.html",
    "dev-a.html", "dev-b.html", "dev-c.html", "dev-options.html",
}
# Pages that are on the site but no longer in the menu (still reachable by link).
OUT_OF_MENU = {
    "full-limb.html": "Earlier projects", "wheel-chair.html": "Earlier projects",
    "preparing-ntop-input.html": "nTop explainers", "ntop-socket-creation.html": "nTop explainers",
    "pelvic-plane-locator.html": "nTop explainers", "interface-plane-locator.html": "nTop explainers",
    "screw-attachment.html": "nTop explainers", "implicit-viewer.html": "nTop explainers",
    "mesh-tolerance.html": "nTop explainers", "socket-walkthrough.html": "Socket walkthrough (older version)",
    "design-review.html": "Reviews & presentations", "review-editor.html": "Reviews & presentations",
    "design-log.html": "Reviews & presentations", "anatomy-labelling.html": "Learn & Try (editor checklist)",
}


def title_of(path):
    m = re.search(r"<title>(.*?)</title>", path.read_text(encoding="utf-8"), re.S)
    t = html.unescape(re.sub(r"\s+", " ", m.group(1)).strip()) if m else path.stem
    t = re.sub(r"\s*[-|–]\s*Give a Paw\s*$", "", t)
    return re.sub(r"^Give a Paw\s*[-|–]\s*", "", t) or "Home"


def main():
    groups = {}
    for title, links in site_infra.NAV_GROUPS:
        for href, _ in links:
            groups[href] = title.replace("&amp;", "&")
    for region, links in site_infra.HUMAN_REGIONS:
        for href, _ in links:
            groups[href] = "Learn & Try (human anatomy regions)"
    pages = []
    for p in sorted(ROOT.glob("*.html")):
        name = p.name
        if name in PRIVATE:
            continue
        group = "Home" if name == "index.html" else groups.get(name) or OUT_OF_MENU.get(name) or "Not in the menu"
        pages.append({
            "file": name,
            "title": title_of(p),
            "group": group,
            "inMenu": name == "index.html" or name in groups,
            "generated": name in site_infra.META,   # menu, footer and meta come from site_infra.py
        })
    out = ROOT / "dev-pages.js"
    body = json.dumps(pages, indent=1, ensure_ascii=False)
    out.write_text("// Generated by tools/dev_pages.py; do not edit by hand. Lists the public pages for dev.html.\n"
                   f"export const pages = {body};\n", encoding="utf-8", newline="\n")
    print(f"wrote {out.name}: {len(pages)} pages")


if __name__ == "__main__":
    main()
